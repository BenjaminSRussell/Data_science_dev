const getStoryReveal = (npc, relationshipLevel, topic) => {
    const npcStory = CHARACTER_STORIES[npc];
    if (!npcStory) {
        return null;
    }

    const reveals = npcStory.storyReveals.filter(reveal => reveal.relationshipLevel <= relationshipLevel && reveal.topic === topic);
    if (reveals.length > 0) {
        return reveals[reveals.length - 1].dialogue;
    }

    return null;
};

const getPersonalStory = (npc, field) => {
    const npcStory = CHARACTER_STORIES[npc];
    if (!npcStory || !npcStory.personalStory) {
        return null;
    }

    return npcStory.personalStory[field];
};

export { getStoryReveal, getPersonalStory };